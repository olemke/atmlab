function nc_type = gmt_get_nctype(var)
%% gmt_get_nctype 
% Returns the netcdf type of var
%
% OUT nc_type    string containing the netcdf type
% IN  var    input data whos type will be determined
%
% 2011-02-23 created by Salomon Eliasson


str = struct('logical','BYTE','int8','BYTE',...
'int16','SHORT',...
'int32','INT',...
'single','FLOAT',...
'double','DOUBLE',...
'uint8','UBYTE',...
'uint16','USHORT',...
'uint32','UINT',...
'int64','INT64',...
'uint64','UINT64');

if isfield(str,class(var))
    nc_type = str.(class(var));
else
    error('gmtlab:input',...
        'Class %s has no corresponding netcdf type',class(var))
end

