function value = colloc_config(varargin)

% colloc_config Handling of Cloudsat Collocation configuration settings
%
% Similar to 'atmlab'.
%
% $Id$

persistent A

try
    [A,value] = prstnt_struct( A, @colloc_config_defs, varargin );
catch ME
    switch (ME.identifier)
        % see if any aliases can be identified
        case 'atmlab:prstnt_struct:undefined' 
            elem = varargin{1};
            aliases = colloc_config('alias');
            nm = fieldnames(aliases);
            for i = 1:length(nm)
                elem = strrep(elem, nm{i}, aliases.(nm{i}));
            end
            varargin{1} = elem;
            [A,value] = prstnt_struct( A, @colloc_config_defs, varargin);
        otherwise
            ME.rethrow();
    end
end
 
