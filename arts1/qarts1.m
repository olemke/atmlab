% QARTS1   Defines setting fields for ARTS1 calculations
%
%    The function provides default values for all recognised fields and a 
%    description of each field. Default value is normally NaN, but
%    exceptions exist when some standard choice exists. To list default
%    values just type 'qarts1'.
%
%    This function is organised in such way that *qcheck* and *qinfo*
%    can be used.
%
% FORMAT   [Q,I] = qarts1
%        
% OUT   Q  Setting structure with default values for all recognised fields.
%       I  Includes same fields as Q, where the content of each field
%          is a description string (used by *qinfo*).

% 2004-09-07   Created by Patrick Eriksson.


function [Q,I] = qarts1
 
%-----------------------------------------------------------------------------
Q.ABSMODELS = which('arts1_absmodels.cfile');
I.ABSMODELS = [ ...
'An control file excerpt including descriptions of absorption models to', ...
' use (called continua in ARTS1). This shall be a series of calls of', ...
' *cont_descriptionAppend* (call of *cont_descriptionInit* shall NOT be',...
' included.',...
'#   Shall be as a file name. A file containing standard choices is',...
' *arts1_absmodels.cfile*.'
];
%-----------------------------------------------------------------------------
Q.APRIORI_PTZ = NaN;
I.APRIORI_PTZ = [ ...
'Acts as ARTS1 WSV with same name. Specified as a file name.', ...
' Can be NaN if USE_RAW_ATMOSPHERE = 0.'
];
%-----------------------------------------------------------------------------
Q.APRIORI_VMR = NaN;
I.APRIORI_VMR = [ ...
'Acts as ARTS1 WSV with same name. Specified as a file name without', ...
' extensions.', ...
' Can be NaN if USE_RAW_ATMOSPHERE = 0.'
];
%-----------------------------------------------------------------------------
Q.E_GROUND = NaN;
I.E_GROUND = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS.'
];
%-----------------------------------------------------------------------------
Q.EMISSION_ON = 1;
I.EMISSION_ON = [ ...
'Boolean to include emission. If field set to 0, optical thicknesses', ...
' are calculated instead of radiance values.'
];
%-----------------------------------------------------------------------------
Q.F_MONO = NaN;
I.F_MONO = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS.'
];
%-----------------------------------------------------------------------------
Q.HSE_ON = NaN;
I.HSE_ON = [ ...
'Boolean to ensure that Z_ABS fulfils hydrostatic equilibrium with respect',...
' to P_ABS and T_ABS.'
];
%-----------------------------------------------------------------------------
Q.HSE = NaN;
I.HSE = [ ...
'A vector of length 4 with input to WSM *hseSet:', ...
'#   Element 1: reference pressure',...
'#   Element 2: reference altitude',...
'#   Element 3: gravitational acceleration at the geoid surface',...
'#   Element 4: number of calculation iterations (1 or 2 should suffice)'
];
%-----------------------------------------------------------------------------
Q.L_STEP = NaN;
I.L_STEP = [ ...
'As ARTS1 WSV with same name. Must be a scalar.'
];
%-----------------------------------------------------------------------------
Q.LINEDATA = NaN;
I.LINEDATA = [ ...
'The data on spectroscopic lines to use. Can be given in two ways:', ...
'#1. As a file name. All formats handled by ARTS1 can then be used. See', ...
' LINEFORMAT. The reading is not restricted to any frequency range.', ...
'#2. As an array of line data. Format described in *arts_write_linefile*,',...
' and such an array can be loaded by *arts_read_linefile*. The value of',...
' is here neglected as this data can only be in ARTS format. It is allowed',...
' to set the field to be empty.' 
];
%-----------------------------------------------------------------------------
Q.LINEFORMAT = NaN;
I.LINEFORMAT = [ ...
'The format on spectroscopic data, if provided as a file (see LINEDATA).', ...
'#   Possible formats are ''Arts'', ''Hitran'', ''Jpl'' and ''Mytran2''.', ...
' Note that these strings must be given exactly as stated here (first',...
' upper case etc.).'
];
%-----------------------------------------------------------------------------
Q.LINESHAPE = 'Voigt_Kuntz6';
I.LINESHAPE = [ ...
'The line shape to use. The same line shape is used for all tag groups.', ...
' Shall be a string.', ...
' Do "arts -d ineshape_per_tgDefine" to list valid options.'
];
%-----------------------------------------------------------------------------
Q.LINESHAPE_CUTOFF = -1;
I.LINESHAPE_CUTOFF = [ ...
'The line shape cut-off to apply. The same cut-off is used for all tag', ...
' groups. A value of -1 means no cut-off.', ...
' Do "arts -d ineshape_per_tgDefine" for further information.'
];
%-----------------------------------------------------------------------------
Q.LINESHAPE_FACTOR = 'quadratic';
I.LINESHAPE_FACTOR = [ ...
'The line shape normalisation factor to apply. The same factor is used', ...
' for all tag groups. Shall be a string.', ...
' Do "arts -d lineshape_per_tgDefine" for valid options.'
];
%-----------------------------------------------------------------------------
Q.P_ABS = NaN;
I.P_ABS = [ ...
'As ARTS1 WSV with same name.', ...
' Can either be a vector, or name of a relevant file. File names must end', ...
' with .aa or .ab to indicate which ARTS1 data format that is used.' 
];
%-----------------------------------------------------------------------------
Q.R_GEOID = constants( 'EARTH_RADIUS' );;
I.R_GEOID = [ ...
'As ARTS1 WSV with same name. Must be a scalar.'
];
%-----------------------------------------------------------------------------
Q.REFR_ON = NaN;
I.REFR_ON = [ ...
'Boolean to include refraction.'
];
%-----------------------------------------------------------------------------
Q.REFR_LFAC = NaN;
I.REFR_LFAC = [ ...
'This factor determines the step length used during the ray tracing',...
' performed when considering refraction.',...
' The step length applied is L_STEP divided by REFR_LFAC.',...
' Accordingly, this factor gives how many ray tracing steps that are',...
' performed for each step of the LOS.'
];
%-----------------------------------------------------------------------------
Q.T_ABS = NaN;
I.T_ABS = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS. Can be NaN if USE_RAW_ATMOSPHERE = 1.'
];
%-----------------------------------------------------------------------------
Q.T_GROUND = NaN;
I.T_GROUND = [ ...
'As ARTS1 WSV with same name. Must be a scalar.'
];
%-----------------------------------------------------------------------------
Q.T_SPACE = constants( 'CBGR' );
I.T_SPACE = [ ...
'Blackbody temperature of radiation entering the atmosphere from space'
];
%-----------------------------------------------------------------------------
Q.TGS = [];
I.TGS = [ ...
'Specification of species tag groups.', ...
' Atmlab format for tag groups is specified in * arts_tgs_cnvrt*.'
];
%-----------------------------------------------------------------------------
Q.USE_RAW_ATMOSPHERE = NaN;
I.USE_RAW_ATMOSPHERE = [ ...
'Boolean to decide if T_ABS, Z_ABS and VMRS shall be used (option 0) or',...
' APRIORI_PTZ and APRIORI_VMRS (option 1).'
];
%-----------------------------------------------------------------------------
Q.VMRS = NaN;
I.VMRS = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS. Can be NaN if USE_RAW_ATMOSPHERE = 1.'
];
%-----------------------------------------------------------------------------
Q.Y_UNIT = 'RJ';
I.Y_UNIT = [ ...
'Radiance unit. The following options are supported:', ...
'#   ''1''      : Basic radiances [W/m2/Hz/sr]',...
'#   ''RJ''     : Conversion to brightness temperature by Rayleigh-Jeans.',...
'#   ''Planck'' : Conversion to brightness temperature by Planck.'
];
%-----------------------------------------------------------------------------
Q.Z_ABS = NaN;
I.Z_ABS = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS. Can be NaN if USE_RAW_ATMOSPHERE = 1.'
];
%-----------------------------------------------------------------------------
Q.Z_GROUND = NaN;
I.Z_GROUND = [ ...
'As ARTS1 WSV with same name. Must be a scalar.'
];
%-----------------------------------------------------------------------------
Q.Z_PLAT = NaN;
I.Z_PLAT = [ ...
'As ARTS1 WSV with same name. Must be a scalar.'
];
%-----------------------------------------------------------------------------
Q.ZA_PENCIL = NaN;
I.ZA_PENCIL = [ ...
'As ARTS1 WSV with same name.', ...
' For allowed input formats see P_ABS.'
];
%-----------------------------------------------------------------------------


