% ASG   Defines setting fields for the ARTS scene generator (ASG)
%
%    The function provides default values for all recognised fields and a 
%    description of each field. Default value is normally NaN, but
%    exceptions exist when some standard choice exists. To list default
%    values just type 'asg'.
%
%    This function is organised in such way that *qcheck* and *qinfo*
%    can be used.
%
% FORMAT   [A,I] = asg
%        
% OUT   QA Setting structure with default values for all recognised fields.
%       I  Includes same fields as Q, where the content of each field
%          is a description string (used by *qinfo*).

% 2007-10-09   Created by Patrick Eriksson.


function [A,I] = asg

%-----------------------------------------------------------------------------
A.ABS_SPECIES = [];
I.ABS_SPECIES = [ ...
'Description of gas species profiles, as a structure array. For example:',...
'#   A.ABS_SPECIES(3).SOURCE = ''/home/...',...
'#The structure array has the following fields:',...
'#   NAME   : Name on species. Basically free format, but one array item ',...
'with the name ''Water vapour'' is expected.',...
'#   SOURCE : Data source. Can either be the name on an xml file (only ',...
'file format supported), or be data in gformat. The data can be given in ',...
'any atmospheric dimensionality in both cases. If necessary, data are ',...
'expanded automatically to ATMOSPHERE_DIM.',...
'#   TAG    : ARTS absorption tag name (e.g. {''H2O'',''H2O-MPM89''}).',...
];
%-----------------------------------------------------------------------------
A.ATMOSPHERE_DIM = NaN;
I.ATMOSPHERE_DIM = [ ...
'Atmospheric dimensionality (as the ARTS WSV with the same name).'
];
%-----------------------------------------------------------------------------
A.HSE = [];
I.HSE = [ ...
'Data for calculating hydrostatic equilibrium. The field shall be a ',...
'structure with the following fields (see also *asg_hydrostat*):',...
'#    P0 : Reference pressure. A scalar value, that is applied for all ',...
'latitudes and longitudes.',...
'#    Z0 : Reference altitudes. Data shall be given using the gformat ',...
'(stripped version accepted, see R_GEOID). ',...
'Input can have a lower dimensionality than expected for ATMOSPHERE_DIM.'
];
%-----------------------------------------------------------------------------
A.LAT0 = NaN;
I.LAT0 = [ ...
'Latitude where to place loaded data not containing a latitude position.'
];
%-----------------------------------------------------------------------------
A.LAT_GRID = NaN;
I.LAT_GRID = [ ...
'Latitude grid (as the ARTS WSV with the same name). The grid can be ',...
'set explicitly by giving a vector (length>=2). An automatic choice can ',...
'also be made by *asg_atmgrids*. This function produces the union of ',...
'grids of loaded data. In this case, LAT_GRID shall be a scalar and is ',...
'taken as the minimum distance between grid points.'
];
%-----------------------------------------------------------------------------
A.LON0 = NaN;
I.LON0 = [ ...
'As LAT0 but for longitude.'
];
%-----------------------------------------------------------------------------
A.LON_GRID = NaN;
I.LON_GRID = [ ...
'As LAT_GRID but for longitude.'
];
%-----------------------------------------------------------------------------
A.P_GRID = NaN;
I.P_GRID = [ ...
'Functionality as for LAT_GRID, with the exception that grid minimum ',...
'spacing (the scalar choice) is given in pressure decades.'
];
%-----------------------------------------------------------------------------
A.R_GEOID = [];
I.R_GEOID = [ ...
'Geoid radius (as the ARTS WSV with the same name).',...
'#    Input shall follow the gformat, but a stripped version is accepted ',...
'where source, name and unit fields can be left out. That is, required ',...
'fields are dim, data, grid1, and possibly also higher grids.'
];
%-----------------------------------------------------------------------------
A.T = [];
I.T = [ ...
'Description of atmospheric temperatures. A structure with the following ',...
'fields:',...
'#   SOURCE : As same sub-field in ABS_SPECIES.'
];
%-----------------------------------------------------------------------------
A.Z_SURFACE = [];
I.Z_SURFACE = [ ...
'Surface altitude (as the ARTS WSV with the same name). Data shall be ',...
'given using the gformat (stripped version accepted, see R_GEOID). '
];
%-----------------------------------------------------------------------------

