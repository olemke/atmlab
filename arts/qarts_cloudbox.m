% QARTS_CLOUDBOX   Defines setting fields for ARTS cloudbox calculations
%
%    The function provides default values for all recognised fields and a 
%    description of each field. Default value is normally NaN, but
%    exceptions exist when some standard choice exists. To list default
%    values just type 'qarts_cloudbox'.
%
%    This function is organised in such way that *qcheck* and *qinfo*
%    can be used.
%
% FORMAT   [Q,I] = qarts_cloudbox
%        
% OUT   Q  Setting structure with default values for all recognised fields.
%       I  Includes same fields as Q, where the content of each field
%          is a description string (used by *qinfo*).

% 2005-03-14   Created by Patrick Eriksson.


function [Q,I] = qarts_cloudbox
 
%-----------------------------------------------------------------------------
Q.LIMITS = NaN;
I.LIMITS = [ ...
'Cloudbox limits. Given as a vector, with length 2-6 depending on the ',...
'atmospheric dimensionality. The vertical extension is given in ',...
'geometrical altitude.'
];
%-----------------------------------------------------------------------------
Q.METHOD = NaN;
I.METHOD = [ ...
'Calculation method for scattering. Allowed options are:',...
'#   ''DOIT'' : Discrete ordinate iterative method',...
'#   ''MC''   : Backward Monte Carlo'
];
%-----------------------------------------------------------------------------
Q.METHOD_PRMTRS = NaN;
I.METHOD_PRMTRS = [ ...
'Parameters and data for scattering calculation method, given as a ',...
'structure. The set of fields of this structure depend on choosen METHOD:',...
'# ',...
'#*** DOIT ***',...
'#   AAA : ',...
'# ',...
'#*** MC ***',...
'#   STD_ERR         : As the keyword argument with same name.',...
'#   MAX_TIME        : As the keyword argument with same name.',...
'#   MAX_ITER        : As the keyword argument with same name.',...
'#   RNG_SEED        : As the keyword argument with same name.',...
'#   INCOMING_LOOKUP : As the keyword argument with same name.',...
'#   Z_FIELD_IS_1D   : As the keyword argument with same name.'
];
%-----------------------------------------------------------------------------
Q.PND_FIELD = NaN;
I.PND_FIELD = [ ...
'Field of particle number densities. There are here two options:',...
'#   1. The WSV *pnd_field* can be specified directly. Can then be given ',...
'either as the name of a XML file, or as a Matlab variable.',...
'#   2. As the name of files with the field of individual particle ',...
'species. The field must then be a cell array of strings. These files',...
'must match SCAT_DATA and are used as input to *ParticleTypeAdd*.',...
'#   The same option must be used for PND_FIELD and SCAT_DATA.'
];
%-----------------------------------------------------------------------------
Q.SCAT_DATA = NaN;
I.SCAT_DATA = [ ...
'Single scattering data. There are here two options:',...
'#   1. The WSV *scat_data_raw* can be specified directly. Can then be ',...
'given either as the name of a XML file, or as a Matlab variable.',...
'#   2. As the name of files with data of individual particle ',...
'species. The field must then be a cell array of strings. These files ',...
'must match PND_FIELD and are used as input to *ParticleTypeAdd*.',...
'#   The same option must be used for PND_FIELD and SCAT_DATA.'
];
%-----------------------------------------------------------------------------
