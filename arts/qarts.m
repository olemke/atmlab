% QARTS   Defines setting fields for arts calculations
%
%    The function defines all Qarts fields. All fields are initiated to {}, that
%    indicates that no value has been specified. No data will be transfered to
%    arts for fields later not given a non-{} value. The settings are converted
%    tocontrol files by *qarts2cfile*. This function adds automatically method
%    calls for saving (standard) variables. everything else must be specified by
%    the qarts fields or be handled by include control files.
%
%    Allowed formats differ between the fields. For information about a specific
%    field, type e.g.:
%       qinfo( @qarts, 'ABSORPTION' );
%
%    This function is organised in such way that *qcheck* and *qinfo* can be
%    used.
%
% FORMAT   [Q,I] = qarts
%        
% OUT   Q  Setting structure with default values for all recognised fields.
%       I  Includes same fields as Q, where the content of each field
%          is a description string (used by *qinfo*).

% 2004-09-07   Created by Patrick Eriksson.


