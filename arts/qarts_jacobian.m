% QARTS_JACOBIAN   Defines setting fields for ARTS jacobian calculations
%
%    The function provides default values for all recognised fields and a 
%    description of each field.  To list default values just type 
%    'qarts_jacobian'. The default value for all do-fields is 0.
%
%    This function is organised in such way that *qcheck* and *qinfo*
%    can be used.
%
% FORMAT   [J,I] = qarts_jacobian
%        
% OUT   J  Setting structure with default values for all recognised fields.
%       I  Includes same fields as B, where the content of each field
%          is a description string (used by *qinfo*).

% 2006-08-29   Created by Patrick Eriksson.


function [J,I] = qarts_jacobian


%-----------------------------------------------------------------------------
J.ABS_SPECIES(1).DO     = 0;
J.ABS_SPECIES(1).METHOD = NaN;
J.ABS_SPECIES(1).UNIT   = NaN;
J.ABS_SPECIES(1).GRID1  = NaN;
J.ABS_SPECIES(1).GRID2  = NaN;
J.ABS_SPECIES(1).GRID3  = NaN;
I.ABS_SPECIES = [ ...
'Specification of absorption species jacobians.', ...
'#    This field is an array of structures. These fields are defined:',...
'#     DO     : Flag to do jacobians.', ...
'#     UNIT   : Retrieval unit (''rel'', ''vmr'' or ''nd'').',...
'#     METHOD : Calculation method (''analytical'' or ''perturbation'').',...
'#     DX     : Size of perturbations. Ignored if METHOD = analytical',...
'#     GRID1  : Retrieval grid in pressure dimension.',...
'#     GRID2  : Retrieval grid in latitude dimension.',...
'#     GRID3  : Retrieval grid in longitude dimension.',...
'#See further ''arts -d jacobianAddGas''. The DO field is added to make',...
' it possible to turn off jacobian calculations without removing the ',...
'the definition, for possible later reactivation.',...
'#   These fields are most easily set by the *q_gas_species*. The same ',...
'indexing is used for Q.ABS_SPECIES and J.ABS_SPECIES, but J.ABS_SPECIES ',...
'can be shorter than Q.ABS_SPECIES. No jacobian calculations are performed',...
' for species with no J.ABS_SPECIES entry.'
];
%-----------------------------------------------------------------------------
J.POINTING.DO         = 0;
J.POINTING.DZA        = NaN;
J.POINTING.POLY_ORDER = NaN;
I.POINTING = [ ...
'Structure for specification of pointing offset jacobians. The fields ', ...
'correspond directly to keyword arguments of *jacobianAddPointing*:', ...
'#   DZA         - size of perturbation', ...
'#   POLY_ORDER  - order of the perturbation polynomial.'
];
%-----------------------------------------------------------------------------
